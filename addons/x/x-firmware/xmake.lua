package("x-firmware")
set_kind("addon")
set_homepage("https://github.com/wmem/x-firmware")
set_description("固件镜像、纯 Lua LZ4 和 bsdiff 打包工具")
set_license("MIT")
add_urls("git@github.com:wmem/x-firmware.git")
add_versions("0.1.0", "d440c9f33ca5b707bb37a280d7255b3c866fc087")
on_load(function(package)
    local root = os.getenv("XMAKE_ADDON_SOURCE_ROOT")
    if root then
        local gitdir = path.join(path.absolute(root), "x-firmware", ".git")
        assert(os.isdir(gitdir), "本地工具仓库不存在：" .. gitdir)
        package:set("urls", "file://" .. path.unix(gitdir))
    end
end)
on_install(function(package)
    import("prepare-addon", {rootdir = path.join(os.curdir(), "scripts"), anonymous = true}).install(package)
end)
on_test(function(package)
    assert(os.isfile(package:installdir("modules/api.lua")), "缺少公开 API")
    assert(os.isfile(package:installdir("modules/include/x_firmware/firmware.h")), "缺少共享协议头")
    assert(os.isfile(package:installdir("modules/include/x_firmware/product.h")), "缺少产品信息头")
    assert(os.isfile(package:installdir("modules/licenses/bsdiff.txt")), "缺少算法许可证")
    assert(os.isfile(package:installdir("plugins/x-firmware/xmake.lua")), "缺少命令入口")
end)
package_end()

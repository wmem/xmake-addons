package("x-console")
set_kind("addon")
set_homepage("https://github.com/wmem/x-console")
set_description("显式配置的 Linux/Windows 串口终端")
set_license("MIT")
add_urls("git@github.com:wmem/x-console.git")
add_versions("0.1.0", "eefa744e7132aaa0c51f56c5da614b7349114948")
on_load(function(package)
    local root = os.getenv("XMAKE_ADDON_SOURCE_ROOT")
    if root then
        local gitdir = path.join(path.absolute(root), "x-console", ".git")
        assert(os.isdir(gitdir), "本地工具仓库不存在：" .. gitdir)
        package:set("urls", "file://" .. path.unix(gitdir))
    end
end)
on_install(function(package)
    import("prepare-addon", {rootdir = path.join(os.curdir(), "scripts"), anonymous = true}).install(package)
end)
on_test(function(package)
    assert(os.isfile(package:installdir("modules/api.lua")), "缺少公开API")
    assert(os.isfile(package:installdir("plugins/x-console/main.lua")), "缺少命令入口")
    assert(os.isfile(package:installdir("modules/runtime/terminal.py")), "缺少执行后端")
end)
package_end()
